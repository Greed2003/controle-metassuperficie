int pattern_count(int mode) {
    if (!is_valid_mode(mode)) {
        return 0;
    }
    return mode < 4 ? (1 << mode) : kMaxPatterns;
}

bool get_pattern(int mode, int table, uint32_t& outputs) {
    if (table < 1 || table > pattern_count(mode)) {
        return false;
    }
#if defined(__AVR__)
    outputs = pgm_read_dword(&kPatterns[mode - 1][table - 1]);
#else
    outputs = kPatterns[mode - 1][table - 1];
#endif
    return true;
}

